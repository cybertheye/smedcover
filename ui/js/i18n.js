let lang = "zh";
export const getLang = () => lang;
export function setLang(l) { lang = l === "en" ? "en" : "zh"; document.documentElement.lang = lang === "zh" ? "zh-CN" : "en"; }
export const detectLang = () => ((globalThis.navigator && navigator.language) || "zh").toLowerCase().startsWith("zh") ? "zh" : "en";
/** Looks up a string; {0}, {1}… are replaced with the extra arguments. */
export function t(key, ...args) {
  const e = STR[key];
  const s = e ? e[lang === "en" ? 1 : 0] : key;
  return s.replace(/\{(\d)\}/g, (_, i) => args[i] ?? "");
}
